const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.ATLAS_URL || 'http://127.0.0.1:4173/';
const out = process.env.ATLAS_ARTIFACTS || 'artifacts';
(async()=>{
  fs.mkdirSync(out,{recursive:true});
  const browser=await chromium.launch({headless:true});
  const errors=[];
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base);
  await page.waitForFunction(()=>document.querySelector('#journey-total').textContent!=='—');
  await page.evaluate(()=>document.fonts.ready);
  await page.waitForFunction(()=>{const tiles=[...document.querySelectorAll('.leaflet-tile')];return tiles.length>0 && tiles.every(x=>x.complete&&x.naturalWidth>0&&Number(getComputedStyle(x).opacity)>.99);});
  const expectedStations=await page.evaluate(async()=> (await (await fetch('./data/meta.json')).json()).stations);
  assert.equal(await page.locator('#map .leaflet-pane.leaflet-stations-pane path').count(),expectedStations);
  await page.screenshot({path:out+'/desktop.png',fullPage:true});
  const before=await page.locator('#journey-total').textContent();
  await page.locator('#day-filter').selectOption('weekend');
  await page.waitForFunction(value=>document.querySelector('#journey-total').textContent!==value,before);
  await page.locator('#time-filter').selectOption('am');
  await page.waitForFunction(()=>document.querySelector('#map-status').textContent==='');
  assert.notEqual(before,await page.locator('#journey-total').textContent());
  await page.locator('#community-mode').click();
  assert.equal(await page.locator('#community-mode').getAttribute('aria-pressed'),'true');
  await page.locator('#station-search').fill('waterloo');
  await page.locator('#search-results button').first().click();
  assert(await page.locator('#station-panel').isVisible());
  assert.match(await page.locator('.station-title').textContent(),/waterloo/i);
  await page.locator('[data-direction="in"]').click();
  assert.match(await page.locator('#edge-caption').textContent(),/incoming/);
  await page.screenshot({path:out+'/station.png',fullPage:true});
  await page.locator('#clear-station').click();
  await page.locator('#station-search').fill('zzzz-nothing');
  assert.match(await page.locator('#search-results').textContent(),/No station/);
  await page.locator('#station-search').press('Escape');
  await page.locator('#edge-limit').fill('0');
  assert.match(await page.locator('#edge-caption').textContent(),/^0 strongest/);
  await page.locator('#edge-limit').fill('80');
  await page.locator('#study-tab').click();
  assert(await page.locator('#study').isVisible());
  assert.equal(await page.locator('.study-section').count(),5);
  await page.screenshot({path:out+'/study.png',fullPage:true});
  await page.locator('#return-map').click();
  await page.locator('#day-filter').selectOption('all');
  await page.locator('#time-filter').selectOption('all');
  await page.waitForFunction(()=>document.querySelector('#map-status').textContent==='');
  await page.locator('#activity-mode').click();
  const phone=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
  phone.on('pageerror',e=>errors.push(e.message));
  await phone.goto(base);
  await phone.waitForFunction(()=>document.querySelector('#journey-total').textContent!=='—');
  await phone.evaluate(()=>document.fonts.ready);
  await phone.waitForFunction(()=>{const tiles=[...document.querySelectorAll('.leaflet-tile')];return tiles.length>0 && tiles.every(x=>x.complete&&x.naturalWidth>0&&Number(getComputedStyle(x).opacity)>.99);});
  assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await phone.screenshot({path:out+'/mobile.png',fullPage:true});
  await phone.locator('#station-search').fill('Hyde');
  await phone.locator('#station-search').press('Enter');
  assert(await phone.locator('#station-panel').isVisible());
  await phone.locator('#study-tab').click();
  assert(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await phone.screenshot({path:out+'/mobile-study.png',fullPage:true});
  // A bad data response must give the visitor a working recovery action.
  const bad=await browser.newPage();
  await bad.route('**/data/meta.json',route=>route.fulfill({status:503,body:'unavailable'}));
  await bad.goto(base);
  await bad.getByRole('button',{name:'Try again'}).waitFor();
  assert.match(await bad.locator('#map-status').textContent(),/could not be loaded/);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({desktop:'pass',mobile:'pass',search:'pass',directions:'pass',filters:'pass',study:'pass',loadingError:'pass',javascriptErrors:errors}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
